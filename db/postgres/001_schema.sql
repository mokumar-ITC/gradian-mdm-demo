-- =====================================================================
-- Gradian MDM - schema for PostgreSQL 13+
-- Product hierarchy: Product Family -> Product Type -> Model -> Size -> Product
-- Idempotent: safe to run again on an existing database.
-- Next: 002_product_master_seed.sql (data), 003_demo_users.sql (demo / test only).
-- All timestamps are timestamptz and written by the app in UTC.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS mdm;
CREATE SCHEMA IF NOT EXISTS publish;

-- ---------------------------------------------------------------------
-- 1. Sign-in accounts. Levels: 1 = Viewer, 2 = Maker, 3 = Checker, 4 = Admin
--    password_hash holds a PBKDF2-SHA256 hash, never a plain password.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mdm.user_account (
    login          varchar(100) PRIMARY KEY,
    display_name   varchar(255),
    level_no       smallint     NOT NULL CHECK (level_no BETWEEN 1 AND 4),
    level_desc     varchar(50),
    password_hash  varchar(255),
    is_active      boolean      NOT NULL DEFAULT true,
    last_login     timestamptz,
    created_date   timestamptz  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_user_account_login ON mdm.user_account (lower(login));

-- ---------------------------------------------------------------------
-- 2. Admin column settings (Administration > Column Editing).
--    A column with no row is editable and uses its built-in label.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mdm.column_edit_setting (
    table_key     varchar(50)  NOT NULL,
    column_key    varchar(100) NOT NULL,
    is_editable   boolean      NOT NULL DEFAULT true,
    display_name  varchar(100),                 -- NULL = built-in label
    updated_by    varchar(255),
    updated_date  timestamptz  NOT NULL DEFAULT now(),
    PRIMARY KEY (table_key, column_key)
);

-- ---------------------------------------------------------------------
-- 3. Hierarchy levels (names shown in the app)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mdm.product_hierarchy_level (
    level_no      smallint     PRIMARY KEY,
    level_name    varchar(50)  NOT NULL,
    source_field  varchar(50)  NOT NULL      -- column in the source workbook
);

INSERT INTO mdm.product_hierarchy_level (level_no, level_name, source_field) VALUES
    (1, 'Product Family', 'Product_Family'),
    (2, 'Product Type',   'Product_Type'),
    (3, 'Model',          'Model'),
    (4, 'Size',           'Size')
ON CONFLICT (level_no) DO UPDATE SET level_name = EXCLUDED.level_name, source_field = EXCLUDED.source_field;

-- ---------------------------------------------------------------------
-- 4. Hierarchy nodes (one tree). A name is unique under its parent only,
--    because the same Product Type (e.g. AHU) sits under several families.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mdm.product_hierarchy (
    node_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_node_id  bigint       REFERENCES mdm.product_hierarchy (node_id) ON DELETE RESTRICT,
    level_no        smallint     NOT NULL REFERENCES mdm.product_hierarchy_level (level_no),
    node_name       varchar(255) NOT NULL,
    node_path       varchar(1000) NOT NULL,     -- 'Family > Type > Model > Size'
    isactive        boolean      NOT NULL DEFAULT true,
    createdby       varchar(255),
    updatedby       varchar(255),
    createddate     timestamptz  DEFAULT now(),
    updateddate     timestamptz,
    CONSTRAINT ck_product_hierarchy_root CHECK ((level_no = 1) = (parent_node_id IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_product_hierarchy_name
    ON mdm.product_hierarchy (coalesce(parent_node_id, 0), lower(node_name));
CREATE INDEX IF NOT EXISTS ix_product_hierarchy_parent ON mdm.product_hierarchy (parent_node_id);

-- ---------------------------------------------------------------------
-- 5. Products. Each product hangs off the deepest hierarchy level it has.
--    Product_Code repeats in the source, so product_id is the key and
--    product_name is the unique business key.
--    updatestatus (maker / checker state): PendingApproval | Approved | Rejected | UpdateDirectly
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mdm.product_master (
    product_id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    node_id                   bigint        NOT NULL REFERENCES mdm.product_hierarchy (node_id) ON DELETE RESTRICT,
    product_name              varchar(255)  NOT NULL,
    product_code              varchar(50),
    siop_model                varchar(50),
    siop_tier                 varchar(50),
    sections_per_unit         integer,
    sale_price_per_unit       numeric(14,2),
    sale_price_per_hour       numeric(12,2),
    default_supply_source     varchar(20),
    est_fab_hours             numeric(10,2),
    est_assembly_hours        numeric(10,2),
    fab_lbr_hrs_pct           numeric(7,2),
    assmb_lbr_hrs_pct         numeric(7,2),
    qty_fans                  integer,
    qty_coils                 integer,
    qty_panels                integer,
    standard_unit_multiplier  numeric(7,2),
    status                    varchar(20)   NOT NULL,
    capacity_group            varchar(100),
    source_row                integer,      -- row number in the source workbook
    isactive                  boolean       NOT NULL DEFAULT true,
    createdby                 varchar(255),
    updatedby                 varchar(255),
    createddate               timestamptz   DEFAULT now(),
    updateddate               timestamptz,
    updatestatus              varchar(50),
    lastmodifiedbyrole        varchar(50),
    remarks                   varchar(4000),
    CONSTRAINT ck_product_master_status CHECK (status IN ('Active', 'Inactive', 'Archived'))
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_product_master_name ON mdm.product_master (lower(product_name));
CREATE INDEX IF NOT EXISTS ix_product_master_node   ON mdm.product_master (node_id);
CREATE INDEX IF NOT EXISTS ix_product_master_code   ON mdm.product_master (product_code);
CREATE INDEX IF NOT EXISTS ix_product_master_status ON mdm.product_master (status);

-- ---------------------------------------------------------------------
-- 6. Change requests (maker / checker). A Maker's edit is stored here as
--    PendingApproval and reaches mdm.product_master only when a Checker approves.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mdm.product_master_audit (
    auditid                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id                bigint        NOT NULL REFERENCES mdm.product_master (product_id) ON DELETE CASCADE,
    product_name              varchar(255)  NOT NULL,
    product_code              varchar(50),
    siop_model                varchar(50),
    siop_tier                 varchar(50),
    sections_per_unit         integer,
    sale_price_per_unit       numeric(14,2),
    sale_price_per_hour       numeric(12,2),
    default_supply_source     varchar(20),
    est_fab_hours             numeric(10,2),
    est_assembly_hours        numeric(10,2),
    fab_lbr_hrs_pct           numeric(7,2),
    assmb_lbr_hrs_pct         numeric(7,2),
    qty_fans                  integer,
    qty_coils                 integer,
    qty_panels                integer,
    standard_unit_multiplier  numeric(7,2),
    status                    varchar(20)   NOT NULL,
    capacity_group            varchar(100),
    changetype                varchar(20)   NOT NULL DEFAULT 'Update',
    approvalstatus            varchar(50)   NOT NULL,   -- PendingApproval | Approved | Rejected | UpdateDirectly
    makerid                   varchar(255),
    checkerid                 varchar(255),
    changetimestamp           timestamptz   NOT NULL DEFAULT now(),
    approvaltimestamp         timestamptz,
    lastmodifiedbyrole        varchar(50),
    remarks                   varchar(4000),            -- maker's reason for the change
    checker_remarks           varchar(4000),            -- checker's approve / reject comment
    CONSTRAINT ck_product_audit_status CHECK (status IN ('Active', 'Inactive', 'Archived'))
);
CREATE INDEX IF NOT EXISTS ix_product_audit_status  ON mdm.product_master_audit (approvalstatus);
CREATE INDEX IF NOT EXISTS ix_product_audit_product ON mdm.product_master_audit (product_id);
-- At most one open request per product (the app checks this too)
CREATE UNIQUE INDEX IF NOT EXISTS ux_product_audit_pending
    ON mdm.product_master_audit (product_id) WHERE approvalstatus = 'PendingApproval';

-- ---------------------------------------------------------------------
-- 7. Field dictionary (sheet "Product Master Fields" of the workbook)
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS mdm.product_master_field (
    field_order   smallint     PRIMARY KEY,
    source_field  varchar(100) NOT NULL UNIQUE,   -- header in the workbook
    column_name   varchar(100) NOT NULL,          -- column in mdm.product_master / hierarchy level
    description   varchar(4000)
);

-- ---------------------------------------------------------------------
-- 8. Each product with its full hierarchy path. The tree is at most four levels
--    deep, so plain joins are used (same definition as the Fabric script).
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW mdm.vw_product_master AS
WITH chain AS (
    SELECT h.node_id, h.node_path,
           h.level_no  AS l0, h.node_name  AS n0,
           p1.level_no AS l1, p1.node_name AS n1,
           p2.level_no AS l2, p2.node_name AS n2,
           p3.level_no AS l3, p3.node_name AS n3
      FROM mdm.product_hierarchy h
      LEFT JOIN mdm.product_hierarchy p1 ON p1.node_id = h.parent_node_id
      LEFT JOIN mdm.product_hierarchy p2 ON p2.node_id = p1.parent_node_id
      LEFT JOIN mdm.product_hierarchy p3 ON p3.node_id = p2.parent_node_id
)
SELECT p.product_id, p.node_id, c.node_path,
       CASE 1 WHEN c.l0 THEN c.n0 WHEN c.l1 THEN c.n1 WHEN c.l2 THEN c.n2 WHEN c.l3 THEN c.n3 END AS product_family,
       CASE 2 WHEN c.l0 THEN c.n0 WHEN c.l1 THEN c.n1 WHEN c.l2 THEN c.n2 END                     AS product_type,
       CASE 3 WHEN c.l0 THEN c.n0 WHEN c.l1 THEN c.n1 END                                          AS model,
       CASE 4 WHEN c.l0 THEN c.n0 END                                                              AS size,
       p.product_name, p.product_code, p.siop_model, p.siop_tier, p.sections_per_unit,
       p.sale_price_per_unit, p.sale_price_per_hour, p.default_supply_source,
       p.est_fab_hours, p.est_assembly_hours, p.fab_lbr_hrs_pct, p.assmb_lbr_hrs_pct,
       p.qty_fans, p.qty_coils, p.qty_panels, p.standard_unit_multiplier,
       p.status, p.capacity_group, p.source_row, p.isactive,
       p.createdby, p.createddate, p.updatedby, p.updateddate,
       p.updatestatus, p.lastmodifiedbyrole, p.remarks
  FROM mdm.product_master p
  JOIN chain c ON c.node_id = p.node_id;

-- ---------------------------------------------------------------------
-- 9. Publish view for downstream systems, using the workbook's headers
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW publish.product_master_vw AS
SELECT product_family           AS "Product_Family",
       product_type             AS "Product_Type",
       model                    AS "Model",
       size                     AS "Size",
       siop_model               AS "SIOP_Model",
       siop_tier                AS "SIOP_Tier",
       product_name             AS "Product_Name",
       product_code             AS "Product_Code",
       sections_per_unit        AS "Sections_Per_Unit",
       sale_price_per_unit      AS "Sale_Price_Per_Unit",
       sale_price_per_hour      AS "Sale_Price_Per_Hour",
       default_supply_source    AS "Default_Supply_Source",
       est_fab_hours            AS "Est_Fab_Hours",
       est_assembly_hours       AS "Est_Assembly_Hours",
       fab_lbr_hrs_pct          AS "Fab_Lbr_Hrs_%",
       assmb_lbr_hrs_pct        AS "Assmb_Lbr_Hrs_%",
       qty_fans                 AS "Qty_Fans",
       qty_coils                AS "Qty_Coils",
       qty_panels               AS "Qty_Panels",
       standard_unit_multiplier AS "Standard_Unit_Multiplier",
       status                   AS "Status",
       capacity_group           AS "Capacity Group"
  FROM mdm.vw_product_master
 WHERE isactive;
